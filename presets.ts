export function getEffectiveFacilityCost(
  facility: Pick<Facility, 'cost' | 'budgetExcluded'>,
): number {
  return facility.budgetExcluded ? 0 : facility.cost;
}

export function getFacilityDisplayName(facility: Facility, lang: Language): string {
  if (facility.customDisplayName) {
    return facility.nameKo || facility.name;
  }
  if (lang === 'ko') {
    return facility.nameKo || SUBTYPE_SIMPLE_LABELS[facility.subtype]?.ko || facility.name;
  }
  if (lang === 'en') {
    return facility.name || SUBTYPE_SIMPLE_LABELS[facility.subtype]?.en || facility.nameKo || facility.id;
  }
  const baseLabel = SUBTYPE_SIMPLE_LABELS[facility.subtype]?.[lang];
  if (!baseLabel) {
    return facility.name || facility.nameKo || facility.id;
  }
  const suffixMatch = (facility.nameKo || facility.name || '').match(/(?:\s+|-)([0-9]+|[A-D])$/i);
  return suffixMatch ? `${baseLabel} ${suffixMatch[1]}` : baseLabel;
}

