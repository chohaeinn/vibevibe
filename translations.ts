export function formatLocalizedCurrency(usdAmount: number, lang: Language): string {
  const safeUsd = Number.isFinite(usdAmount) ? Math.max(0, usdAmount) : 0;
  if (lang === 'ko') {
    const manWon = Math.round((safeUsd * 1350) / 10000);
    if (manWon >= 10000) {
      const eok = Math.floor(manWon / 10000);
      const rem = manWon % 10000;
      return rem > 0 ? `₩${eok}억 ${rem.toLocaleString()}만` : `₩${eok}억 원`;
    }
    return `₩${manWon.toLocaleString()}만`;
  }
  if (lang === 'ja') {
    const manYen = Math.round((safeUsd * 150) / 10000);
    return `¥${manYen.toLocaleString()}万`;
  }
  if (lang === 'zh') {
    const rmb = Math.round(safeUsd * 7.2);
    return `¥${rmb.toLocaleString()}`;
  }
  if (lang === 'es' || lang === 'fr') {
    const eur = Math.round(safeUsd * 0.92);
    return `€${eur.toLocaleString()}`;
  }
  return `$${Math.round(safeUsd).toLocaleString()}`;
}

